"""Index a local directory into a Graphora graph. Deterministic, no LLM."""

from __future__ import annotations

import fnmatch
import logging
import subprocess
from pathlib import Path
from typing import TYPE_CHECKING, Callable

from graphora.parser import ParsedFile, is_supported_code_file, parse_code_file
from graphora.store import GraphStore

if TYPE_CHECKING:
    from graphora.store import GraphBackend

logger = logging.getLogger(__name__)

DEFAULT_IGNORES = [
    ".git", "node_modules", "venv", ".venv", "__pycache__", "dist", "build",
    ".tox", ".mypy_cache", ".pytest_cache", "vendor", ".idea", ".vscode",
]

ProgressCallback = Callable[[str, int, int, str], None]


# Markers that tools write into the first lines of files they generate.
_GENERATED_MARKERS = (
    "@generated",
    "do not edit",
    "code generated by",
    "generated from",
    "auto-generated",
    "autogenerated",
    "this file was automatically generated",
)
_GENERATED_SUFFIXES = (".min.js", ".pb.go", "_pb2.py", "_pb2_grpc.py", ".g.dart", ".designer.cs")
_HEADER_BYTES = 1024


def is_generated_file(path: Path) -> bool:
    """True for minified/protobuf output or files whose header says they are generated."""
    if path.name.lower().endswith(_GENERATED_SUFFIXES):
        return True
    try:
        with path.open("rb") as handle:
            header = handle.read(_HEADER_BYTES).decode("utf-8", errors="ignore").lower()
    except OSError:
        return False
    head = "\n".join(header.splitlines()[:5])
    return any(marker in head for marker in _GENERATED_MARKERS)


def _git_visible_files(root: Path) -> list[Path] | None:
    """Tracked plus untracked-but-not-ignored files, or None outside a git work tree."""
    try:
        result = subprocess.run(
            ["git", "ls-files", "-z", "--cached", "--others", "--exclude-standard"],
            cwd=root,
            capture_output=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    names = result.stdout.decode("utf-8", errors="surrogateescape").split("\0")
    return [root / name for name in sorted(set(names)) if name]


def collect_source_files(
    root: str | Path,
    ignores: list[str] | None = None,
    include_generated: bool = False,
) -> list[Path]:
    """Supported source files under `root`.

    Inside a git work tree this honours .gitignore (via `git ls-files`);
    elsewhere it walks the directory. DEFAULT_IGNORES and `ignores` apply
    either way, and generated files are skipped unless `include_generated`.
    """
    root = Path(root).resolve()
    ignore_names = set(DEFAULT_IGNORES) | set(ignores or [])
    candidates = _git_visible_files(root)
    if candidates is None:
        candidates = sorted(root.rglob("*"))
    files: list[Path] = []
    for path in candidates:
        if not path.is_file() or not is_supported_code_file(str(path)):
            continue
        relative = path.relative_to(root)
        if any(part in ignore_names for part in relative.parts):
            continue
        if any(fnmatch.fnmatch(str(relative), pat) for pat in ignore_names if "*" in pat):
            continue
        if not include_generated and is_generated_file(path):
            logger.info("Skipping generated file %s", relative)
            continue
        files.append(path)
    return files


def _parse_or_skip(rel: str, content: str) -> ParsedFile | None:
    """Parse one file; a parser failure skips that file instead of aborting the run."""
    try:
        return parse_code_file(rel, content)
    except Exception as exc:  # noqa: BLE001 - one bad file must not kill the index
        logger.warning("Skipping file that failed to parse %s: %s: %s", rel, type(exc).__name__, exc)
        return None


def index_repository(
    root: str | Path,
    project: str | None = None,
    host: str = "localhost",
    port: int = 6379,
    ignores: list[str] | None = None,
    store: GraphBackend | None = None,
    on_progress: ProgressCallback | None = None,
    include_generated: bool = False,
) -> GraphBackend:
    """Parse every supported file under `root` and build the graph.

    Returns the GraphStore for further queries. Zero LLM calls.

    Raises FileNotFoundError / NotADirectoryError for a bad `root`, and
    ValueError when it holds no supported source files, before touching the
    store: re-indexing replaces the whole graph, so a typo must not wipe it.
    """
    root = Path(root).resolve()
    if not root.exists():
        raise FileNotFoundError(f"{root} does not exist")
    if not root.is_dir():
        raise NotADirectoryError(f"{root} is not a directory")
    files = collect_source_files(root, ignores, include_generated=include_generated)
    if not files:
        raise ValueError(f"{root} has no supported source files; the existing graph was left unchanged")
    project = project or root.name
    store = store or GraphStore(project, host=host, port=port)

    total = len(files)
    parsed_files = []
    for index, path in enumerate(files, start=1):
        rel = str(path.relative_to(root))
        if on_progress:
            on_progress("parsing", index, total, rel)
        try:
            content = path.read_text(encoding="utf-8", errors="replace")
        except OSError as exc:
            logger.warning("Skipping unreadable file %s: %s", rel, exc)
            continue
        parsed = _parse_or_skip(rel, content)
        if parsed is not None:
            parsed_files.append(parsed)

    store.clear()
    for index, parsed in enumerate(parsed_files, start=1):
        if on_progress:
            on_progress("writing", index, total, parsed.path)
        store.write_files([parsed], save=False)  # link_cross_file_calls saves

    if on_progress:
        on_progress("linking", total, total, "cross-file calls")
    linked = store.link_cross_file_calls()
    logger.info("Indexed %s files (%s cross-file call edges) into %s", len(parsed_files), linked, store.graph_name)
    return store


def update_files(
    root: str | Path,
    paths: list[str],
    project: str | None = None,
    host: str = "localhost",
    port: int = 6379,
    store: GraphBackend | None = None,
) -> GraphBackend:
    """Incremental update: re-parse only the given relative paths."""
    root = Path(root).resolve()
    project = project or root.name
    store = store or GraphStore(project, host=host, port=port)
    for rel in paths:
        full = root / rel
        if not full.exists():
            store.delete_file(rel)
            continue
        if not is_supported_code_file(rel) or is_generated_file(full):
            continue
        content = full.read_text(encoding="utf-8", errors="replace")
        parsed = _parse_or_skip(rel, content)
        if parsed is None:
            store.delete_file(rel)
            continue
        store.write_files([parsed], save=False)  # link_cross_file_calls saves
    store.link_cross_file_calls()
    return store
